// importColumn 是导入测试里表的一列：名称、类型，是否自增、是否 GENERATED ALWAYS。
type importColumn struct {
	name, typ      string
	serial, always bool
}

func expectImportColumns(mock sqlmock.Sqlmock, schema, table string, columns ...importColumn) {
	rows := sqlmock.NewRows([]string{"column_name", "data_type", "udt_name", "is_nullable", "column_default", "is_auto_increment", "is_identity_always"})
	for _, c := range columns {
		rows.AddRow(c.name, c.typ, c.typ, "YES", nil, c.serial || c.always, c.always)
	}
	mock.ExpectQuery(columnsSQL).WithArgs(schema, table).WillReturnRows(rows)
}

func texts(values ...string) []dbdriver.ImportValue {
	out := make([]dbdriver.ImportValue, len(values))
	for i, v := range values {
		out[i] = dbdriver.ImportValue{Kind: dbdriver.ImportText, Text: v}
	}
	return out
}

// 追加/更新与追加/跳过用 ON CONFLICT；追加/更新只映射了键时退化成 DO NOTHING。与改动前前端生成的
// 文本逐字一致（原 tableImport.test.ts 的断言）。
func TestImportUpsertAndSkipForPostgreSQL(t *testing.T) {
	session, mock := newMock(t)
	ctx := context.Background()
	users := []importColumn{{name: "id", typ: "integer"}, {name: "name", typ: "text"}}
	generate := func(mode dbdriver.ImportMode, columns []string, row []dbdriver.ImportValue) []string {
		t.Helper()
		expectImportColumns(mock, "appdb", "users", users...)
		statements, err := session.ImportStatements(ctx, "mydb", "appdb.users", dbdriver.ImportRequest{
			Mode: mode, Columns: columns, Keys: []string{"id"}, Rows: [][]dbdriver.ImportValue{row},
		})
		require.NoError(t, err)
		return statements
	}

	assert.Equal(t, []string{`INSERT INTO "appdb"."users" ("id") VALUES ('1') ON CONFLICT ("id") DO NOTHING;`},
		generate(dbdriver.ImportAppendUpdate, []string{"id"}, texts("1")))
	assert.Equal(t, []string{`INSERT INTO "appdb"."users" ("id", "name") VALUES ('1', 'Alice') ON CONFLICT ("id") DO UPDATE SET "name" = excluded."name";`},
		generate(dbdriver.ImportAppendUpdate, []string{"id", "name"}, texts("1", "Alice")))
	assert.Equal(t, []string{`INSERT INTO "appdb"."users" ("id", "name") VALUES ('1', 'Alice') ON CONFLICT ("id") DO NOTHING;`},
		generate(dbdriver.ImportAppendSkip, []string{"id", "name"}, texts("1", "Alice")))
	require.NoError(t, mock.ExpectationsWereMet())
}

// 映射包含 GENERATED ALWAYS 列：插入带 OVERRIDING SYSTEM VALUE（多行插入同样），追加/更新与更新不改
// 它；serial / GENERATED BY DEFAULT 列照常写、照常更新。
func TestImportWritesGeneratedAlwaysValuesForPostgreSQL(t *testing.T) {
	session, mock := newMock(t)
	ctx := context.Background()
	items := []importColumn{{name: "code", typ: "text"}, {name: "id", typ: "integer", always: true}, {name: "seq", typ: "integer", serial: true}, {name: "name", typ: "text"}}
	generate := func(req dbdriver.ImportRequest) []string {
		t.Helper()
		expectImportColumns(mock, "public", "items", items...)
		statements, err := session.ImportStatements(ctx, "mydb", "public.items", req)
		require.NoError(t, err)
		return statements
	}
	row := texts("A1", "7", "3", "Alice")
	request := func(mode dbdriver.ImportMode, rows ...[]dbdriver.ImportValue) dbdriver.ImportRequest {
		return dbdriver.ImportRequest{Mode: mode, Columns: []string{"code", "id", "seq", "name"}, Keys: []string{"code"}, Rows: rows}
	}

	assert.Equal(t, []string{
		`INSERT INTO "public"."items" ("code", "id", "seq", "name") OVERRIDING SYSTEM VALUE VALUES ('A1', '7', '3', 'Alice');`,
	}, generate(request(dbdriver.ImportAppend, row)))
	extended := request(dbdriver.ImportCopy, row, texts("B2", "8", "4", "Bob"))
	extended.ExtendedInsert, extended.MaxStatementSizeKB = true, 1024
	assert.Equal(t, []string{
		`DELETE FROM "public"."items";`,
		`INSERT INTO "public"."items" ("code", "id", "seq", "name") OVERRIDING SYSTEM VALUE VALUES ('A1', '7', '3', 'Alice'), ('B2', '8', '4', 'Bob');`,
	}, generate(extended))
	assert.Equal(t, []string{
		`INSERT INTO "public"."items" ("code", "id", "seq", "name") OVERRIDING SYSTEM VALUE VALUES ('A1', '7', '3', 'Alice') ` +
			`ON CONFLICT ("code") DO UPDATE SET "seq" = excluded."seq", "name" = excluded."name";`,
	}, generate(request(dbdriver.ImportAppendUpdate, row)))
	assert.Equal(t, []string{`UPDATE "public"."items" SET "seq" = '3', "name" = 'Alice' WHERE "code" = 'A1';`},
		generate(request(dbdriver.ImportUpdate, row)))

	// 没映射 GENERATED ALWAYS 列：不带 OVERRIDING。
	assert.Equal(t, []string{`INSERT INTO "public"."items" ("code", "seq") VALUES ('A1', '3');`}, generate(dbdriver.ImportRequest{
		Mode: dbdriver.ImportAppend, Columns: []string{"code", "seq"}, Rows: [][]dbdriver.ImportValue{texts("A1", "3")},
	}))
	require.NoError(t, mock.ExpectationsWereMet())
}

// bytea 写成 '\x…'::bytea（空字节同样），其余照旧。
func TestImportBinaryForPostgreSQL(t *testing.T) {
	session, mock := newMock(t)
	expectImportColumns(mock, "appdb", "files", importColumn{name: "id", typ: "integer"}, importColumn{name: "payload", typ: "bytea"})

	statements, err := session.ImportStatements(context.Background(), "mydb", "appdb.files", dbdriver.ImportRequest{
		Mode: dbdriver.ImportAppend, Columns: []string{"id", "payload"},
		Rows: [][]dbdriver.ImportValue{
			{{Kind: dbdriver.ImportText, Text: "1"}, {Kind: dbdriver.ImportBinary, Hex: "48656c6c6f"}},
			{{Kind: dbdriver.ImportText, Text: "2"}, {Kind: dbdriver.ImportBinary}},
		},
	})
	require.NoError(t, err)
	assert.Equal(t, []string{
		`INSERT INTO "appdb"."files" ("id", "payload") VALUES ('1', '\x48656c6c6f'::bytea);`,
		`INSERT INTO "appdb"."files" ("id", "payload") VALUES ('2', '\x'::bytea);`,
	}, statements)
	require.NoError(t, mock.ExpectationsWereMet())
}

// 列的类别按 information_schema 的 data_type 判断。
func TestColumnCategoriesForPostgreSQL(t *testing.T) {
	for columnType, want := range map[string]dbdriver.ColumnCategory{
		"integer": dbdriver.CategoryNumber, "numeric": dbdriver.CategoryNumber, "double precision": dbdriver.CategoryNumber,
		"date": dbdriver.CategoryDate, "timestamp without time zone": dbdriver.CategoryDateTime,
		"timestamp with time zone": dbdriver.CategoryDateTime, "bytea": dbdriver.CategoryBinary,
		"text": dbdriver.CategoryText, "interval": dbdriver.CategoryText, "daterange": dbdriver.CategoryText,
	} {
		assert.Equal(t, want, dialect{}.ColumnCategory(columnType), columnType)
	}
}
