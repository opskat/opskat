// CreateTableSQL 写整条建表：CREATE TABLE（列定义，自增与按写法的默认值见 sqldb.NewColumnSQL；主键写在表定义
// 里），之后按请求的次序建其余索引，再写表注释、列注释（按列的次序）与索引注释（按索引的次序）。没有用到这些的
// 请求与共用的写法逐字一致。
func (d dialect) CreateTableSQL(tables sqldb.Tables, database string, req dbdriver.CreateTableRequest) ([]string, error) {
	tableRef := tables.TableRef(database, req.Name)
	target := targetOf(tableRef)
	columns := req.Definitions()
	defs := make([]string, 0, len(columns)+1)
	for _, column := range columns {
		def, err := sqldb.NewColumnSQL(d, sqldb.DefinitionLiterals, tables.QuoteIdent, column)
		if err != nil {
			return nil, err
		}
		defs = append(defs, def)
	}
	var indexes, comments []string
	for _, index := range req.Indexes {
		if index.Type == dbdriver.IndexTypePrimary {
			clause, err := primaryKeyClause(index)
			if err != nil {
				return nil, err
			}
			defs = append(defs, clause)
		} else {
			statement, err := target.createIndexSQL(index, false)
			if err != nil {
				return nil, err
			}
			indexes = append(indexes, statement)
		}
		if strings.TrimSpace(index.Comment) != "" {
			statement, err := target.commentOnIndexSQL(index)
			if err != nil {
				return nil, err
			}
			comments = append(comments, statement)
		}
	}

	statements := []string{fmt.Sprintf("CREATE TABLE %s (\n  %s\n)", tableRef, strings.Join(defs, ",\n  "))}
	statements = append(statements, indexes...)
	if comment := strings.TrimSpace(req.Comment); comment != "" {
		statement, err := d.TableCommentSQL(tableRef, comment)
		if err != nil {
			return nil, err
		}
		statements = append(statements, statement)
	}
	for _, column := range columns {
		if strings.TrimSpace(column.Comment) == "" {
			continue
		}
		statement, err := d.ColumnCommentSQL(tableRef, column)
		if err != nil {
			return nil, err
		}
		statements = append(statements, statement)
	}
	return append(statements, comments...), nil
}

// TableCommentSQL 是 COMMENT ON TABLE。
func (dialect) TableCommentSQL(tableRef, comment string) (string, error) {
	value, err := commentValue(comment)
	if err != nil {
		return "", err
	}
	return "COMMENT ON TABLE " + tableRef + " IS " + value, nil
}

// ColumnCommentSQL 是 COMMENT ON COLUMN。
func (dialect) ColumnCommentSQL(tableRef string, column dbdriver.ColumnDefinition) (string, error) {
	value, err := commentValue(column.Comment)
	if err != nil {
		return "", err
	}
	return "COMMENT ON COLUMN " + tableRef + "." + quoteIdent(strings.TrimSpace(column.Name)) + " IS " + value, nil
}
