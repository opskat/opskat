// --- 列：默认值写法与自增 ---

var (
	// quotedDefaultPattern 匹配目录里带（或不带）类型转换的字符串常量默认值：'abc'::text、'-1'::integer、
	// '{1,2}'::integer[]、'101'::"bit"。第一组是引号里的原文（'' 是转义的单引号）。类型转换之后还有别的
	// （'a'::text || 'b'::text）的不匹配。
	quotedDefaultPattern = regexp.MustCompile(`^'((?:[^']|'')*)'(?:::[A-Za-z_"][A-Za-z0-9_ ."]*(?:\(\d+(?:,\s*\d+)?\))?(?:\[\])*)?$`)
	// nullDefaultPattern 匹配 NULL 与带类型转换的 NULL（NULL::character varying）。
	nullDefaultPattern = regexp.MustCompile(`(?i)^NULL(?:::[A-Za-z_"][A-Za-z0-9_ ."]*(?:\(\d+(?:,\s*\d+)?\))?(?:\[\])*)?$`)
	// plainValuePattern 匹配目录里不加引号的常量：非负数字（负数目录写成 '-1'::integer）与布尔。
	plainValuePattern = regexp.MustCompile(`(?i)^(\d+(\.\d+)?([eE][-+]?\d+)?|true|false)$`)
	// integerTypePattern 匹配能作 IDENTITY 的整数类型。
	integerTypePattern = regexp.MustCompile(`(?i)^\s*(smallint|integer|int|bigint|int2|int4|int8)\s*$`)
)

// ClassifyDefault 按 information_schema.columns.column_default 判定已有列的默认值写法。没有默认值（IDENTITY
// 列也没有）是「无」；NULL（含 NULL::类型）是 NULL；字符串常量（去掉类型转换，成对的单引号还原成一个）、数字与布尔是值；
// 其余——函数（now()、gen_random_uuid()）、序列（serial 的 nextval(...)）、运算——是表达式，原样写回。
// 值写回时一律写成加引号的字符串（sqldb.DefinitionLiterals），PostgreSQL 按列类型解释它，与原来的常量等价。
func (dialect) ClassifyDefault(column sqldb.AlterableColumn) (dbdriver.DefaultKind, string) {
	if column.Row["column_default"] == nil {
		return dbdriver.DefaultKindNone, ""
	}
	value := strings.TrimSpace(column.DefaultValue)
	if nullDefaultPattern.MatchString(value) {
		return dbdriver.DefaultKindNull, ""
	}
	if match := quotedDefaultPattern.FindStringSubmatch(value); match != nil {
		return dbdriver.DefaultKindValue, strings.ReplaceAll(match[1], "''", "'")
	}
	if plainValuePattern.MatchString(value) {
		return dbdriver.DefaultKindValue, value
	}
	return dbdriver.DefaultKindExpression, column.DefaultValue
}

// AutoIncrementSQL 是自增列的 GENERATED BY DEFAULT AS IDENTITY（与 serial 不同，不另建要单独授权的序列）。
// 只有整数类型能作 IDENTITY；IDENTITY 列不能再有默认值（PostgreSQL 拒绝两者同时出现）。
func (dialect) AutoIncrementSQL(column dbdriver.ColumnDefinition) (string, error) {
	if !integerTypePattern.MatchString(column.Type) {
		return "", fmt.Errorf("column %q: an identity column needs an integer type (smallint, integer or bigint), not %q",
			column.Name, strings.TrimSpace(column.Type))
	}
	_, hasDefault, err := sqldb.DefaultSQL(sqldb.DefinitionLiterals, column)
	if err != nil {
		return "", err
	}
	if hasDefault {
		return "", fmt.Errorf("column %q: an identity column cannot also have a default value", column.Name)
	}
	return "GENERATED BY DEFAULT AS IDENTITY", nil
}

// autoIncrementing 报告读出的一列自增：IDENTITY 列，或默认值取序列的 serial 列（同 TableColumns 的
// is_auto_increment）。已有列的自增只显示、不能改。
func autoIncrementing(row map[string]any) bool {
	return strings.EqualFold(sqldb.PickString(row, "is_identity"), "YES") ||
		strings.HasPrefix(sqldb.PickString(row, "column_default"), "nextval(")
}

// --- 读索引 ---

// indexesSQL 读一张表的索引：每个索引的每一列一行，按在索引里的位置（键列在前，INCLUDE 列在后），主键在最前，
// 其余按名字。键列数取 indoption 的长度：它每个键列一项（INCLUDE 列没有），各版本通用（indnkeyatts 要 11 起）。
// 表达式键没有列名（attnum 为 0），pg_get_indexdef 按位置给出表达式原文（只有这一列，不带操作符类与次序）。
// column_option 是 indoption 的位：1 降序、2 NULLS FIRST。约束只认这张表自己的主键 / 唯一 / 排除约束（外键约束的
// conindid 指向被引用表的索引）。
const indexesSQL = "SELECT ic.relname AS index_name, ix.indisprimary AS is_primary, ix.indisunique AS is_unique, " +
	"am.amname AS method, COALESCE(con.contype::text, '') AS constraint_type, COALESCE(con.condeferrable, false) AS is_deferrable, " +
	"s.pos > array_length(ix.indoption::int2[], 1) AS is_include, COALESCE(a.attname, '') AS column_name, " +
	"pg_get_indexdef(ix.indexrelid, s.pos::int, true) AS column_text, COALESCE(ix.indoption[s.pos - 1], 0) AS column_option, " +
	"COALESCE(op.opcdefault, true) AS default_opclass, " +
	"COALESCE(ix.indcollation[s.pos - 1] NOT IN (0, a.attcollation), false) AS other_collation, " +
	"COALESCE(pg_get_expr(ix.indpred, ix.indrelid, true), '') AS predicate, " +
	"COALESCE(obj_description(ix.indexrelid, 'pg_class'), '') AS index_comment, " +
	"(ic.reloptions IS NOT NULL OR ic.reltablespace <> 0) AS has_storage, pg_get_indexdef(ix.indexrelid) AS index_def " +
	"FROM pg_class t " +
	"JOIN pg_namespace n ON n.oid = t.relnamespace " +
	"JOIN pg_index ix ON ix.indrelid = t.oid " +
	"JOIN pg_class ic ON ic.oid = ix.indexrelid " +
	"JOIN pg_am am ON am.oid = ic.relam " +
	"LEFT JOIN pg_constraint con ON con.conindid = ix.indexrelid AND con.conrelid = t.oid AND con.contype IN ('p', 'u', 'x') " +
	"CROSS JOIN LATERAL generate_series(1, ix.indnatts) AS s(pos) " +
	"LEFT JOIN pg_attribute a ON a.attrelid = t.oid AND a.attnum = ix.indkey[s.pos - 1] " +
	"LEFT JOIN pg_opclass op ON op.oid = ix.indclass[s.pos - 1] " +
	"WHERE n.nspname = $1 AND t.relname = $2 " +
	"ORDER BY ix.indisprimary DESC, ic.relname, s.pos"

// takenIndexNamesSQL 读 schema 里这张表的索引之外的全部关系名：索引名与表、视图、序列、其他表的索引同在
// schema 的名字空间里，与其中任何一个重名都建不成。
const takenIndexNamesSQL = "SELECT c.relname FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace " +
	"WHERE n.nspname = $1 AND c.oid NOT IN (SELECT ix.indexrelid FROM pg_index ix JOIN pg_class t ON t.oid = ix.indrelid " +
	"WHERE t.relnamespace = n.oid AND t.relname = $2) " +
	"ORDER BY c.relname"

// 设计器无法原样重建的已有索引的原因（给用户看）：只读，只能删除。
const (
	readOnlyExpression       = "It has an expression key, which the designer cannot recreate."
	readOnlyPartial          = "It is a partial index (WHERE %s), which the designer cannot recreate."
	readOnlyInclude          = "It has INCLUDE columns (%s), which the designer cannot recreate."
	readOnlyOperatorClass    = "A key column uses a non-default operator class, which the designer cannot recreate."
	readOnlyCollation        = "A key column uses a non-default collation, which the designer cannot recreate."
	readOnlyNullsOrder       = "A key column has a non-default NULLS FIRST / LAST order, which the designer cannot recreate."
	readOnlyMethod           = "It uses the index method %q, which the designer does not offer."
	readOnlyStorage          = "It has storage parameters or a tablespace, which the designer cannot recreate."
	readOnlyNullsNotDistinct = "It treats NULLs as not distinct (NULLS NOT DISTINCT), which the designer cannot recreate."
	readOnlyDeferrable       = "It backs a deferrable constraint, which the designer cannot recreate."
	readOnlyExclusion        = "It backs an EXCLUDE constraint, which the designer cannot recreate."
)

// pg_index.indoption 的位。
const (
	indexOptionDescending = 1
	indexOptionNullsFirst = 2
)

// pg_constraint.contype 里支撑索引的约束（主键是 p）：这里要分辨的是唯一与排除。
const (
	constraintUnique    = "u"
	constraintExclusion = "x"
)

// pgIndex 是 indexesSQL 读出的一个索引。
type pgIndex struct {
	name, method, predicate, comment, definition string
	// constraint 是索引支撑的约束的 contype（p / u / x），普通索引为空。
	constraint                           string
	primary, unique, deferrable, storage bool
	keys                                 []pgIndexKey
	include                              []string
}

// pgIndexKey 是索引的一个键列。
type pgIndexKey struct {
	column dbdriver.IndexColumn
	// 以下是设计器表示不了的写法。
	otherNullsOrder, otherOperatorClass, otherCollation bool
}

// readIndexes 用 indexesSQL 读出表的索引，按查询的次序。
func readIndexes(ctx context.Context, conn *sql.Conn, schema, table string) ([]pgIndex, error) {
	records, err := sqldb.QueryRecords(ctx, conn, indexesSQL, schema, table)
	if err != nil {
		return nil, err
	}
	var indexes []pgIndex
	position := map[string]int{}
	for _, row := range records {
		name := sqldb.PickString(row, "index_name")
		i, seen := position[name]
		if !seen {
			i = len(indexes)
			position[name] = i
			indexes = append(indexes, pgIndex{
				name:       name,
				method:     sqldb.PickString(row, "method"),
				constraint: sqldb.PickString(row, "constraint_type"),
				predicate:  sqldb.PickString(row, "predicate"),
				comment:    sqldb.PickString(row, "index_comment"),
				definition: sqldb.PickString(row, "index_def"),
				primary:    flag(row, "is_primary"),
				unique:     flag(row, "is_unique"),
				deferrable: flag(row, "is_deferrable"),
				storage:    flag(row, "has_storage"),
			})
		}
		index := &indexes[i]
		column := sqldb.PickString(row, "column_name")
		if flag(row, "is_include") {
			if column == "" {
				column = sqldb.PickString(row, "column_text")
			}
			index.include = append(index.include, column)
			continue
		}
		option, err := strconv.Atoi(sqldb.PickString(row, "column_option"))
		if err != nil {
			return nil, fmt.Errorf("index %q: column option: %w", name, err)
		}
		descending := option&indexOptionDescending != 0
		key := pgIndexKey{
			column: dbdriver.IndexColumn{Name: column, Descending: descending},
			// 默认的空值次序：升序 NULLS LAST、降序 NULLS FIRST。
			otherNullsOrder:    descending != (option&indexOptionNullsFirst != 0),
			otherOperatorClass: !flag(row, "default_opclass"),
			otherCollation:     flag(row, "other_collation"),
		}
		if column == "" {
			key.column.Name, key.column.Expression = sqldb.PickString(row, "column_text"), true
		}
		index.keys = append(index.keys, key)
	}
	return indexes, nil
}

// flag 取一行里的布尔列。
func flag(row map[string]any, key string) bool { return sqldb.PickString(row, key) == "true" }

// meta 是对象浏览里的索引：键列（表达式键是表达式原文）与 INCLUDE 列分开。
func (i pgIndex) meta() dbdriver.IndexMeta {
	columns := make([]string, len(i.keys))
	for k, key := range i.keys {
		columns[k] = key.column.Name
	}
	return dbdriver.IndexMeta{Name: i.name, Columns: columns, Unique: i.unique, Include: i.include}
}

// indexDefinition 是改表模型里的索引：类型、键列、INCLUDE 列、方法与注释；设计器写不回原样的带只读原因
// （有几处时给第一处）。
func (i pgIndex) indexDefinition() dbdriver.IndexDefinition {
	index := dbdriver.IndexDefinition{
		Name:    i.name,
		Type:    dbdriver.IndexTypeNormal,
		Columns: make([]dbdriver.IndexColumn, len(i.keys)),
		Include: i.include,
		Options: map[string]any{indexMethodOption: i.method},
		Comment: i.comment,
	}
	switch {
	case i.primary:
		index.Type = dbdriver.IndexTypePrimary
	case i.unique:
		index.Type = dbdriver.IndexTypeUnique
	}
	for k, key := range i.keys {
		index.Columns[k] = key.column
		switch {
		case key.column.Expression:
			markReadOnly(&index, readOnlyExpression)
		case key.otherOperatorClass:
			markReadOnly(&index, readOnlyOperatorClass)
		case key.otherCollation:
			markReadOnly(&index, readOnlyCollation)
		case key.otherNullsOrder:
			markReadOnly(&index, readOnlyNullsOrder)
		}
	}
	if i.predicate != "" {
		markReadOnly(&index, fmt.Sprintf(readOnlyPartial, i.predicate))
	}
	if len(i.include) > 0 {
		markReadOnly(&index, fmt.Sprintf(readOnlyInclude, strings.Join(i.include, ", ")))
	}
	if !slices.Contains(indexMethods, i.method) {
		markReadOnly(&index, fmt.Sprintf(readOnlyMethod, i.method))
	}
	if i.storage {
		markReadOnly(&index, readOnlyStorage)
	}
	// PostgreSQL 15 起的 NULLS NOT DISTINCT 只在定义里看得到（pg_index 的列 15 之前没有）。
	if strings.Contains(i.definition, " NULLS NOT DISTINCT") {
		markReadOnly(&index, readOnlyNullsNotDistinct)
	}
	if i.deferrable {
		markReadOnly(&index, readOnlyDeferrable)
	}
	if i.constraint == constraintExclusion {
		markReadOnly(&index, readOnlyExclusion)
	}
	return index
}

// markReadOnly 标出索引只读的原因；已有原因时保留第一个。
func markReadOnly(index *dbdriver.IndexDefinition, reason string) {
	if index.ReadOnlyReason == "" {
		index.ReadOnlyReason = reason
	}
}

// --- 写索引 ---

// indexTarget 是写索引语句的那张表：加好引号的表引用，与索引名要带的 schema 前缀——索引与表同 schema，
// 表引用不带 schema（按 search_path 解析）时索引名也不带。
type indexTarget struct {
	tableRef     string
	schemaPrefix string
}

// targetOf 从 TableRef 给出的表引用（"schema"."table" 或 "table"，标识符里的引号成对）取出 schema 前缀：
// 第一个标识符到不成对的引号为止，其后是点就是 schema。
func targetOf(tableRef string) indexTarget {
	for i := 1; i < len(tableRef); i++ {
		if tableRef[i] != '"' {
			continue
		}
		if i+1 < len(tableRef) && tableRef[i+1] == '"' {
			i++
			continue
		}
		if i+1 < len(tableRef) && tableRef[i+1] == '.' {
			return indexTarget{tableRef: tableRef, schemaPrefix: tableRef[:i+2]}
		}
		break
	}
	return indexTarget{tableRef: tableRef}
}

// indexRef 是索引名的引用（带表的 schema）。
func (t indexTarget) indexRef(name string) string { return t.schemaPrefix + quoteIdent(name) }

func (dialect) IndexEditing() *dbdriver.IndexEditing { return indexEditing }

// IndexSQL 是建一个索引的语句：普通 / 唯一索引是 CREATE [UNIQUE] INDEX，主键是 ALTER TABLE … ADD PRIMARY KEY。
// 索引注释另是一条 COMMENT ON INDEX（建表与改表时由方言在建索引之后写上）。
func (dialect) IndexSQL(tableRef string, index dbdriver.IndexDefinition) (string, error) {
	return targetOf(tableRef).createIndexSQL(index, false)
}

// DropIndexSQL 是删一个普通索引的 DROP INDEX。支撑主键 / 唯一 / 排除约束的索引要随约束删
// （ALTER TABLE … DROP CONSTRAINT）：只凭名字分不出，改表时由 AlterTableSQL 查过约束再选写法（alterIndexes）。
func (dialect) DropIndexSQL(tableRef, name string) (string, error) {
	return targetOf(tableRef).dropIndexSQL(name, false), nil
}

// dropIndexSQL 删一个索引；constraint 表示它支撑一个约束，连约束一起删。
func (t indexTarget) dropIndexSQL(name string, constraint bool) string {
	if constraint {
		return "ALTER TABLE " + t.tableRef + " DROP CONSTRAINT " + quoteIdent(name)
	}
	return "DROP INDEX " + t.indexRef(name)
}

// createIndexSQL 建一个索引。主键写成 ALTER TABLE … ADD [CONSTRAINT 名] PRIMARY KEY；uniqueConstraint 表示把
// 唯一索引写成唯一约束（ADD CONSTRAINT … UNIQUE，重建原本支撑唯一约束的索引时用）；其余是 CREATE [UNIQUE]
// INDEX [名] ON 表 [USING 方法] (列 [DESC], …)。没有名字时由 PostgreSQL 取名。
func (t indexTarget) createIndexSQL(index dbdriver.IndexDefinition, uniqueConstraint bool) (string, error) {
	if index.Type == dbdriver.IndexTypePrimary {
		clause, err := primaryKeyClause(index)
		if err != nil {
			return "", err
		}
		return "ALTER TABLE " + t.tableRef + " ADD " + clause, nil
	}
	if uniqueConstraint {
		clause, err := constraintClause(index, "UNIQUE")
		if err != nil {
			return "", err
		}
		return "ALTER TABLE " + t.tableRef + " ADD " + clause, nil
	}
	if len(index.Columns) == 0 {
		return "", fmt.Errorf("index %q has no columns", index.Name)
	}
	statement := "CREATE INDEX "
	if index.Type == dbdriver.IndexTypeUnique {
		statement = "CREATE UNIQUE INDEX "
	}
	if name := strings.TrimSpace(index.Name); name != "" {
		statement += quoteIdent(name) + " "
	}
	statement += "ON " + t.tableRef
	if method, ok := index.Options[indexMethodOption].(string); ok {
		statement += " USING " + method
	}
	parts := make([]string, len(index.Columns))
	for i, column := range index.Columns {
		parts[i] = quoteIdent(strings.TrimSpace(column.Name))
		if column.Descending {
			parts[i] += " DESC"
		}
	}
	return statement + " (" + strings.Join(parts, ", ") + ")", nil
}

// primaryKeyClause 是主键的 [CONSTRAINT 名] PRIMARY KEY (列, …)：建表时写在表定义里，改表时跟在 ADD 后面。
func primaryKeyClause(index dbdriver.IndexDefinition) (string, error) {
	return constraintClause(index, "PRIMARY KEY")
}

// constraintClause 是主键 / 唯一约束的 [CONSTRAINT 名] 种类 (列, …)。约束的索引只能是升序的 btree：别的方法与
// 降序以 error 拒绝，而不是悄悄丢掉。
func constraintClause(index dbdriver.IndexDefinition, kind string) (string, error) {
	if len(index.Columns) == 0 {
		return "", fmt.Errorf("index %q has no columns", index.Name)
	}
	if method, ok := index.Options[indexMethodOption].(string); ok && method != "btree" {
		return "", fmt.Errorf("index %q: a %s is always a btree index, not %s", index.Name, kind, method)
	}
	parts := make([]string, len(index.Columns))
	for i, column := range index.Columns {
		if column.Descending {
			return "", fmt.Errorf("index %q: the columns of a %s cannot be descending", index.Name, kind)
		}
		parts[i] = quoteIdent(strings.TrimSpace(column.Name))
	}
	clause := kind + " (" + strings.Join(parts, ", ") + ")"
	if name := strings.TrimSpace(index.Name); name != "" {
		clause = "CONSTRAINT " + quoteIdent(name) + " " + clause
	}
	return clause, nil
}

// commentOnIndexSQL 写索引注释；空注释写 IS NULL（清掉）。没有名字的索引由 PostgreSQL 取名，写不了注释。
func (t indexTarget) commentOnIndexSQL(index dbdriver.IndexDefinition) (string, error) {
	name := strings.TrimSpace(index.Name)
	if name == "" {
		return "", fmt.Errorf("an index without a name cannot have a comment (%q)", strings.TrimSpace(index.Comment))
	}
	value, err := commentValue(index.Comment)
	if err != nil {
		return "", err
	}
	return "COMMENT ON INDEX " + t.indexRef(name) + " IS " + value, nil
}

// commentValue 是 COMMENT ON … IS 后面的内容：注释的字符串常量，空注释是 NULL。
func commentValue(comment string) (string, error) {
	if strings.TrimSpace(comment) == "" {
		return "NULL", nil
	}
	return sqldb.DefinitionLiterals.Literal(comment, "")
}

// indexConstraintsSQL 读表上支撑索引的约束（主键、唯一、排除）：名字与种类。约束的名字就是它的索引的名字。
const indexConstraintsSQL = "SELECT con.conname, con.contype::text AS contype FROM pg_constraint con " +
	"JOIN pg_class t ON t.oid = con.conrelid JOIN pg_namespace n ON n.oid = t.relnamespace " +
	"WHERE n.nspname = $1 AND t.relname = $2 AND con.contype IN ('p', 'u', 'x')"

// alterIndexes 写改表里索引的两半（见 sqldb.IndexDropStatements / IndexCreateStatements 的次序约定）：drops 写在
// 列的改动之前，creates 写在之后。与共用写法的不同：
//   - 现有索引支撑约束时随约束删（ALTER TABLE … DROP CONSTRAINT）——要先查这张表的约束；
//   - 只改了名字或注释的现有索引不重建，写成 ALTER INDEX … RENAME TO 与 COMMENT ON INDEX；新名字是另一个也只改名
//     的索引现在的名字（两个索引互换名字）时照样重建，免得改名撞上还没改走的名字；
//   - 重建原本支撑唯一约束、改完仍是升序 btree 唯一索引的，写回唯一约束（ADD CONSTRAINT … UNIQUE），不悄悄变成
//     唯一索引；
//   - 索引注释在建索引之后一条 COMMENT ON INDEX。
//
// creates 的次序：改名，建索引（按请求的次序），注释。
func alterIndexes(ctx context.Context, conn *sql.Conn, change sqldb.TableChange) (drops, creates []string, err error) {
	if len(change.IndexDrops) == 0 && len(change.Indexes) == 0 {
		return nil, nil, nil
	}
	target := targetOf(change.TargetRef)
	constraints := map[string]string{}
	if len(change.IndexDrops) > 0 || slices.ContainsFunc(change.Indexes, func(c sqldb.IndexChange) bool { return !c.IsNew() }) {
		schema, table := splitSchemaTable(change.Table)
		records, err := sqldb.QueryRecords(ctx, conn, indexConstraintsSQL, schema, table)
		if err != nil {
			return nil, nil, fmt.Errorf("index constraints: %w", err)
		}
		for _, record := range records {
			constraints[sqldb.PickString(record, "conname")] = sqldb.PickString(record, "contype")
		}
	}

	renamedColumns := map[string]string{}
	for _, column := range change.Columns {
		if column.Renamed {
			renamedColumns[column.Current.Name] = column.Column.Name
		}
	}
	cosmetic := make([]bool, len(change.Indexes))
	kept := map[string]bool{}
	for i, changed := range change.Indexes {
		if !changed.IsNew() && onlyNameOrComment(*changed.Current, changed.Index, renamedColumns) {
			cosmetic[i] = true
			kept[changed.Current.Name] = true
		}
	}
	for i, changed := range change.Indexes {
		name := strings.TrimSpace(changed.Index.Name)
		if cosmetic[i] && name != changed.Current.Name && kept[name] {
			cosmetic[i] = false
		}
	}

	for _, dropped := range change.IndexDrops {
		drops = append(drops, target.dropIndexSQL(dropped.Name, constraints[dropped.Name] != ""))
	}
	var renames, builds, comments []string
	for i, changed := range change.Indexes {
		index := changed.Index
		name := strings.TrimSpace(index.Name)
		if cosmetic[i] {
			if name != changed.Current.Name {
				renames = append(renames, "ALTER INDEX "+target.indexRef(changed.Current.Name)+" RENAME TO "+quoteIdent(name))
			}
			if strings.TrimSpace(index.Comment) != strings.TrimSpace(changed.Current.Comment) {
				statement, err := target.commentOnIndexSQL(index)
				if err != nil {
					return nil, nil, err
				}
				comments = append(comments, statement)
			}
			continue
		}
		uniqueConstraint := false
		if !changed.IsNew() {
			drops = append(drops, target.dropIndexSQL(changed.Current.Name, constraints[changed.Current.Name] != ""))
			uniqueConstraint = constraints[changed.Current.Name] == constraintUnique && fitsUniqueConstraint(index)
		}
		statement, err := target.createIndexSQL(index, uniqueConstraint)
		if err != nil {
			return nil, nil, err
		}
		builds = append(builds, statement)
		if strings.TrimSpace(index.Comment) != "" {
			statement, err := target.commentOnIndexSQL(index)
			if err != nil {
				return nil, nil, err
			}
			comments = append(comments, statement)
		}
	}
	creates = append(append(renames, builds...), comments...)
	return drops, creates, nil
}

// onlyNameOrComment 报告现有索引（列名按列的改名换成新名字）与改完的样子只差名字或注释。
func onlyNameOrComment(current, index dbdriver.IndexDefinition, renamedColumns map[string]string) bool {
	current.Columns = slices.Clone(current.Columns)
	for i, column := range current.Columns {
		if renamed, ok := renamedColumns[column.Name]; ok && !column.Expression {
			current.Columns[i].Name = renamed
		}
	}
	current.Name, current.Comment = index.Name, index.Comment
	return current.Equal(index)
}

// fitsUniqueConstraint 报告唯一索引能写成唯一约束：唯一、升序、btree。
func fitsUniqueConstraint(index dbdriver.IndexDefinition) bool {
	if index.Type != dbdriver.IndexTypeUnique {
		return false
	}
	if method, ok := index.Options[indexMethodOption].(string); ok && method != "btree" {
		return false
	}
	return !slices.ContainsFunc(index.Columns, func(c dbdriver.IndexColumn) bool { return c.Descending })
}

