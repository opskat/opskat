// dumpSourceSQL 是往返的样例库：非 public 的 schema、用到与没用到的枚举、GENERATED ALWAYS 与 BY DEFAULT 身份列、
// serial、生成列、主键 / 唯一 / CHECK、外键（自引用，以及 owners 与 pets 互相引用成环）、部分索引、注释，
// 含非 UTF-8 字节的 bytea、超过 2^53 的 bigint、NULL 与引号；依赖另一个视图的视图（名字排在前面）、两个重载的
// 函数、一个过程、触发器与它的函数（在数据之后建，导入数据时不能触发）。序列被推到比数据大的位置。
const dumpSourceSQL = `CREATE SCHEMA app;
CREATE TYPE public.mood AS ENUM ('happy', 'it''s ok', 'sad');
CREATE TYPE app.unused AS ENUM ('x');
CREATE TABLE public.owners (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  name text NOT NULL UNIQUE,
  mood public.mood DEFAULT 'happy',
  best_pet_id integer,
  big bigint,
  name_upper text GENERATED ALWAYS AS (upper(name)) STORED,
  CONSTRAINT owners_name_check CHECK (length(name) > 0)
);
CREATE TABLE public.pets (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id bigint REFERENCES public.owners (id) ON DELETE CASCADE,
  parent_id integer REFERENCES public.pets (id),
  photo bytea,
  note text
);
ALTER TABLE public.owners ADD CONSTRAINT owners_best_pet_fk FOREIGN KEY (best_pet_id) REFERENCES public.pets (id);
CREATE INDEX pets_note_partial ON public.pets (note) WHERE note IS NOT NULL;
COMMENT ON TABLE public.owners IS 'it''s owners';
COMMENT ON COLUMN public.pets.note IS 'free text';
CREATE TABLE app.events (
  id serial PRIMARY KEY,
  owner_id bigint REFERENCES public.owners (id),
  happened_at timestamptz DEFAULT now(),
  payload text
);
INSERT INTO public.owners (name, mood, big) VALUES ('O''Brien', 'it''s ok', 9007199254740993), ('Ann', NULL, NULL);
INSERT INTO public.pets (owner_id, parent_id, photo, note) VALUES
  (1, NULL, '\x00ff10fe'::bytea, 'quote '' and "double"'), (1, 1, NULL, NULL), (2, 2, '\x41'::bytea, E'line\nbreak');
UPDATE public.owners SET best_pet_id = 2 WHERE id = 1;
INSERT INTO app.events (owner_id, happened_at, payload) VALUES
  (1, '2026-11-17 08:00:00+00', 'a'), (2, '2026-11-17 09:00:00+00', NULL), (NULL, NULL, 'c');
DELETE FROM app.events WHERE payload = 'c';
SELECT setval(pg_get_serial_sequence('public.owners', 'id'), 50);
CREATE VIEW public.v_owner_pets AS SELECT o.name, p.id AS pet_id FROM public.owners o JOIN public.pets p ON p.owner_id = o.id;
CREATE VIEW public.a_counts AS SELECT name, count(*) AS pets FROM public.v_owner_pets GROUP BY name;
CREATE FUNCTION public.describe(n integer) RETURNS text LANGUAGE sql AS $$ SELECT 'int ' || n $$;
CREATE FUNCTION public.describe(t text) RETURNS text LANGUAGE sql AS $$ SELECT 'text ' || t $$;
CREATE PROCEDURE app.purge(keep integer) LANGUAGE sql AS $$ DELETE FROM app.events WHERE id > keep $$;
CREATE FUNCTION app.stamp() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  NEW.payload := coalesce(NEW.payload, 'stamped');
  RETURN NEW;
END
$$;
CREATE TRIGGER events_stamp BEFORE INSERT ON app.events FOR EACH ROW EXECUTE FUNCTION app.stamp();`

// structureOptions 是全部结构选项（PostgreSQL 不能关闭外键检查，不写删除语句）。
var structureOptions = dbdriver.DumpOptions{Indexes: true, ForeignKeys: true, Views: true, Routines: true, Triggers: true}

// userSchemas 是比对时看的 schema。
const userSchemas = "NOT IN ('pg_catalog', 'information_schema', 'pg_toast')"

// structureQuery 从系统目录读出整个库的结构（不经转储用到的查询），两个库相同就说明结构被还原了。
const structureQuery = `SELECT 'column ' || ROW(table_schema, table_name, ordinal_position, column_name, data_type, udt_schema,
    udt_name, character_maximum_length, numeric_precision, numeric_scale, is_nullable, column_default, is_identity,
    identity_generation, identity_start, identity_increment, identity_minimum, identity_maximum, identity_cycle,
    is_generated, generation_expression)::text
  FROM information_schema.columns WHERE table_schema ` + userSchemas + `
UNION ALL SELECT 'constraint ' || c.conrelid::regclass::text || ' ' || c.conname || ' ' || pg_get_constraintdef(c.oid)
  FROM pg_constraint c JOIN pg_namespace n ON n.oid = c.connamespace WHERE n.nspname ` + userSchemas + ` AND c.contype <> 'n'
UNION ALL SELECT 'index ' || indexdef FROM pg_indexes WHERE schemaname ` + userSchemas + `
UNION ALL SELECT 'sequence ' || ROW(schemaname, sequencename, data_type, start_value, min_value, max_value, increment_by,
    cycle, last_value)::text FROM pg_sequences WHERE schemaname ` + userSchemas + `
UNION ALL SELECT 'owned ' || table_schema || '.' || table_name || '.' || column_name || ' ' ||
    coalesce(pg_get_serial_sequence(format('%I.%I', table_schema, table_name), column_name), '')
  FROM information_schema.columns WHERE table_schema ` + userSchemas + `
UNION ALL SELECT 'comment ' || c.oid::regclass::text || ' ' || coalesce(obj_description(c.oid, 'pg_class'), '') || ' ' ||
    coalesce((SELECT string_agg(a.attname || '=' || col_description(c.oid, a.attnum), ',' ORDER BY a.attnum)
      FROM pg_attribute a WHERE a.attrelid = c.oid AND a.attnum > 0 AND col_description(c.oid, a.attnum) IS NOT NULL), '')
  FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace WHERE n.nspname ` + userSchemas + ` AND c.relkind IN ('r', 'v')
UNION ALL SELECT 'view ' || schemaname || '.' || viewname || ' ' || definition FROM pg_views WHERE schemaname ` + userSchemas + `
UNION ALL SELECT 'routine ' || n.nspname || '.' || p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ') ' ||
    pg_get_functiondef(p.oid)
  FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace WHERE n.nspname ` + userSchemas + `
UNION ALL SELECT 'trigger ' || pg_get_triggerdef(t.oid) FROM pg_trigger t JOIN pg_class c ON c.oid = t.tgrelid
  JOIN pg_namespace n ON n.oid = c.relnamespace WHERE n.nspname ` + userSchemas + ` AND NOT t.tgisinternal
UNION ALL SELECT 'enum ' || n.nspname || '.' || t.typname || ' ' ||
    (SELECT string_agg(e.enumlabel, ',' ORDER BY e.enumsortorder) FROM pg_enum e WHERE e.enumtypid = t.oid)
  FROM pg_type t JOIN pg_namespace n ON n.oid = t.typnamespace WHERE t.typtype = 'e' AND n.nspname ` + userSchemas + `
UNION ALL SELECT 'schema ' || nspname FROM pg_namespace WHERE nspname ` + userSchemas + ` AND nspname NOT LIKE 'pg\_%'
ORDER BY 1`

func queryLines(t *testing.T, db *sql.DB, query string) []string {
	t.Helper()
	rows, err := db.Query(query)
	require.NoError(t, err)
	defer func() { _ = rows.Close() }()
	var lines []string
	for rows.Next() {
		var line string
		require.NoError(t, rows.Scan(&line))
		lines = append(lines, line)
	}
	require.NoError(t, rows.Err())
	return lines
}

// tableData 是每张表的行数与全部行（按行的文本排序）的校验和；生成列、bytea 与 bigint 都在行的文本里。
func tableData(t *testing.T, db *sql.DB) []string {
	t.Helper()
	tables := queryLines(t, db, "SELECT format('%I.%I', table_schema, table_name) FROM information_schema.tables "+
		"WHERE table_schema "+userSchemas+" AND table_type = 'BASE TABLE' ORDER BY 1")
	lines := make([]string, 0, len(tables))
	for _, table := range tables {
		var count int
		var checksum string
		require.NoError(t, db.QueryRow("SELECT count(*), md5(coalesce(string_agg(r::text, '|' ORDER BY r::text), '')) FROM "+table+" r").
			Scan(&count, &checksum))
		lines = append(lines, fmt.Sprintf("%s %d %s", table, count, checksum))
	}
	return lines
}

// nextValues 取每个序列的下一个值（会推进序列，所以在比对完结构之后调用）。
func nextValues(t *testing.T, db *sql.DB) []string {
	t.Helper()
	return queryLines(t, db, "SELECT schemaname || '.' || sequencename || ' ' || nextval(format('%I.%I', schemaname, sequencename)) "+
		"FROM pg_sequences WHERE schemaname "+userSchemas+" ORDER BY 1")
}

// 在一个临时库里建出样例，经 Session.Dump 整库转储（结构和数据），再经 Session.RunScript 运行到另一个名字的空临时库：
// 每条语句都成功，两边的结构（列、约束、索引、序列与当前值、注释、视图、函数、过程、触发器、枚举、schema）、
// 每张表的行数与数据校验和、序列的下一个值都一样；触发器在新库里照样生效。
func TestIntegrationDumpRestoresAWholeDatabaseOnAnEmptyOne(t *testing.T) {
	admin := openDDLDatabase(t, os.Getenv("E2E_POSTGRES_DATABASE"))
	suffix := time.Now().UnixNano()
	source, target := fmt.Sprintf("opskat_dump_src_%d", suffix), fmt.Sprintf("opskat_dump_dst_%d", suffix)
	createScratchDatabase(t, admin, source)
	createScratchDatabase(t, admin, target)
	sourceDB, targetDB := openDDLDatabase(t, source), openDDLDatabase(t, target)
	_, err := sourceDB.Exec(dumpSourceSQL)
	require.NoError(t, err)

	ctx := context.Background()
	var out strings.Builder
	dumped, err := newSession(sourceDB).Dump(ctx, dbdriver.DumpRequest{
		Database: source, Whole: true, WithData: true, Writer: &out, Options: structureOptions,
		Header: dbdriver.DumpHeader{Version: "test", Asset: "pg", Time: time.Now()},
	})
	require.NoError(t, err)
	script := out.String()
	assert.NotContains(t, script, "DROP", "without the drop option the file has no drop statement at all")
	t.Log(script)
	// 表 3 张、视图 2 个、函数 describe 与 stamp、过程 purge、触发器 events_stamp。
	assert.Equal(t, 9, dumped.Objects)
	assert.EqualValues(t, 7, dumped.Rows)

	result, err := newSession(targetDB).RunScript(ctx, dbdriver.ScriptRequest{
		Database: target, Script: strings.NewReader(script), Size: int64(len(script)),
	})
	require.NoError(t, err)
	require.Nil(t, result.Failure, "the dump must run on an empty database")

	assert.Equal(t, queryLines(t, sourceDB, structureQuery), queryLines(t, targetDB, structureQuery))
	assert.Equal(t, tableData(t, sourceDB), tableData(t, targetDB))
	assert.Equal(t, nextValues(t, sourceDB), nextValues(t, targetDB))

	var payload string
	require.NoError(t, targetDB.QueryRow("INSERT INTO app.events (owner_id) VALUES (1) RETURNING payload").Scan(&payload))
	assert.Equal(t, "stamped", payload)
	var described string
	require.NoError(t, targetDB.QueryRow("SELECT public.describe(1) || ' / ' || public.describe('x'::text)").Scan(&described))
	assert.Equal(t, "int 1 / text x", described)
}

// 覆盖还原：勾了「写入删除语句」整库转储，再把文件运行回源库本身——库里还有全部数据、外键（含互相引用成环的）、
// 依赖另一个视图的视图与触发器。删除段先拆掉各表的外键，再删触发器、过程与函数、视图、表、枚举类型（不带
// CASCADE），每条语句都成功；结构（含序列当前值）与每张表的数据都和转储之前一样。
func TestIntegrationDumpOverwritesTheOriginalDatabase(t *testing.T) {
	admin := openDDLDatabase(t, os.Getenv("E2E_POSTGRES_DATABASE"))
	source := fmt.Sprintf("opskat_dump_ovr_%d", time.Now().UnixNano())
	createScratchDatabase(t, admin, source)
	sourceDB := openDDLDatabase(t, source)
	_, err := sourceDB.Exec(dumpSourceSQL)
	require.NoError(t, err)
	structure, data := queryLines(t, sourceDB, structureQuery), tableData(t, sourceDB)

	ctx := context.Background()
	var out strings.Builder
	options := structureOptions
	options.Drops = true
	_, err = newSession(sourceDB).Dump(ctx, dbdriver.DumpRequest{
		Database: source, Whole: true, WithData: true, Writer: &out, Options: options,
		Header: dbdriver.DumpHeader{Version: "test", Asset: "pg", Time: time.Now()},
	})
	require.NoError(t, err)
	script := out.String()
	require.Contains(t, script, `ALTER TABLE IF EXISTS "public"."owners" DROP CONSTRAINT IF EXISTS "owners_best_pet_fk";`)
	for _, line := range strings.Split(script, "\n") {
		if strings.HasPrefix(line, "DROP ") || strings.Contains(line, " DROP CONSTRAINT ") {
			assert.NotContains(t, line, "CASCADE", "drops never cascade")
		}
	}

	result, err := newSession(sourceDB).RunScript(ctx, dbdriver.ScriptRequest{
		Database: source, Script: strings.NewReader(script), Size: int64(len(script)),
	})
	require.NoError(t, err)
	require.Nil(t, result.Failure, "the dump must run back into the database it came from: %+v", result.Failure)
	assert.Zero(t, result.Failed)
	assert.Equal(t, structure, queryLines(t, sourceDB, structureQuery))
	assert.Equal(t, data, tableData(t, sourceDB))
}

// 整个 schema：schema 里的表的列用到别的 schema 的枚举类型（含它的数组）时，这个枚举类型也写进文件（连同它的
// schema），文件在空库上运行得出这些表；schema 里没被用到的枚举照样写出，别的 schema 里没被用到的不写。
func TestIntegrationDumpWholeSchemaWritesTheEnumsItsColumnsUse(t *testing.T) {
	admin := openDDLDatabase(t, os.Getenv("E2E_POSTGRES_DATABASE"))
	suffix := time.Now().UnixNano()
	source, target := fmt.Sprintf("opskat_dump_schema_src_%d", suffix), fmt.Sprintf("opskat_dump_schema_dst_%d", suffix)
	createScratchDatabase(t, admin, source)
	createScratchDatabase(t, admin, target)
	sourceDB, targetDB := openDDLDatabase(t, source), openDDLDatabase(t, target)
	_, err := sourceDB.Exec(`CREATE SCHEMA app;
CREATE SCHEMA lookup;
CREATE TYPE lookup.mood AS ENUM ('happy', 'sad');
CREATE TYPE lookup.level AS ENUM ('low', 'high');
CREATE TYPE lookup.unused AS ENUM ('x');
CREATE TYPE app.state AS ENUM ('open', 'closed');
CREATE TYPE app.spare AS ENUM ('y');
CREATE TABLE app.notes (id integer PRIMARY KEY, mood lookup.mood, levels lookup.level[], state app.state);
INSERT INTO app.notes VALUES (1, 'sad', '{low,high}', 'open'), (2, NULL, NULL, 'closed');`)
	require.NoError(t, err)

	ctx := context.Background()
	var out strings.Builder
	_, err = newSession(sourceDB).Dump(ctx, dbdriver.DumpRequest{
		Database: source, Schema: "app", Whole: true, WithData: true, Writer: &out, Options: structureOptions,
		Header: dbdriver.DumpHeader{Version: "test", Asset: "pg", Time: time.Now()},
	})
	require.NoError(t, err)
	script := out.String()
	t.Log(script)

	result, err := newSession(targetDB).RunScript(ctx, dbdriver.ScriptRequest{
		Database: target, Script: strings.NewReader(script), Size: int64(len(script)),
	})
	require.NoError(t, err)
	require.Nil(t, result.Failure, "the schema dump must run on an empty database: %+v", result.Failure)
	enums := "SELECT n.nspname || '.' || t.typname FROM pg_type t JOIN pg_namespace n ON n.oid = t.typnamespace " +
		"WHERE t.typtype = 'e' ORDER BY 1"
	assert.Equal(t, []string{"app.spare", "app.state", "lookup.level", "lookup.mood"}, queryLines(t, targetDB, enums))
	assert.Equal(t, tableData(t, sourceDB), tableData(t, targetDB))
}

// 不勾「包含索引」：外键引用的列只有唯一索引（不是唯一约束）时，唯一索引照样写出，外键才加得上；浮点列里的
// NaN 与正负无穷照样转储、还原。文件在空库上每条语句都成功，数据一样。
func TestIntegrationDumpWithoutIndexesKeepsUniqueIndexesAndNonFiniteFloats(t *testing.T) {
	admin := openDDLDatabase(t, os.Getenv("E2E_POSTGRES_DATABASE"))
	suffix := time.Now().UnixNano()
	source, target := fmt.Sprintf("opskat_dump_uniq_src_%d", suffix), fmt.Sprintf("opskat_dump_uniq_dst_%d", suffix)
	createScratchDatabase(t, admin, source)
	createScratchDatabase(t, admin, target)
	sourceDB, targetDB := openDDLDatabase(t, source), openDDLDatabase(t, target)
	_, err := sourceDB.Exec(`CREATE TABLE public.parents (id integer PRIMARY KEY, code text NOT NULL);
CREATE UNIQUE INDEX parents_code ON public.parents (code);
CREATE INDEX parents_plain ON public.parents (id, code);
CREATE TABLE public.children (id integer PRIMARY KEY, code text REFERENCES public.parents (code));
CREATE TABLE public.readings (id integer PRIMARY KEY, value double precision, small real);
INSERT INTO public.parents VALUES (1, 'a');
INSERT INTO public.children VALUES (1, 'a');
INSERT INTO public.readings VALUES (1, 'NaN', 'Infinity'), (2, '-Infinity', 1.5), (3, 2.25, 'NaN');`)
	require.NoError(t, err)

	ctx := context.Background()
	var out strings.Builder
	_, err = newSession(sourceDB).Dump(ctx, dbdriver.DumpRequest{
		Database: source, Whole: true, WithData: true, Writer: &out, Options: dbdriver.DumpOptions{ForeignKeys: true},
		Header: dbdriver.DumpHeader{Version: "test", Asset: "pg", Time: time.Now()},
	})
	require.NoError(t, err)
	script := out.String()
	t.Log(script)
	assert.NotContains(t, script, "parents_plain", "indexes that aren't unique stay out")

	result, err := newSession(targetDB).RunScript(ctx, dbdriver.ScriptRequest{
		Database: target, Script: strings.NewReader(script), Size: int64(len(script)),
	})
	require.NoError(t, err)
	require.Nil(t, result.Failure, "the dump must run on an empty database: %+v", result.Failure)
	assert.Equal(t, tableData(t, sourceDB), tableData(t, targetDB))
}

// crossDependencySQL 是视图与函数互相依赖的样例：调用函数的视图（a_doubled 调用 z_double），引用视图的函数
// （BEGIN ATOMIC 的 a_total 读 a_doubled，返回视图行类型的 a_rows），以及调用这个函数的视图（b_summary）。
// 名字的字母序（列出的次序）与依赖相反：视图在前时 a_doubled 建不出，函数在前（驱动给不出依赖时的写法）时
// a_total 与 a_rows 建不出。
const crossDependencySQL = `CREATE TABLE public.items (id integer PRIMARY KEY, price integer NOT NULL);
INSERT INTO public.items VALUES (1, 10), (2, 25);
CREATE FUNCTION public.z_double(n integer) RETURNS integer LANGUAGE sql IMMUTABLE RETURN n * 2;
CREATE VIEW public.a_doubled AS SELECT id, public.z_double(price) AS doubled FROM public.items;
CREATE FUNCTION public.a_total() RETURNS bigint LANGUAGE sql BEGIN ATOMIC SELECT sum(doubled) FROM public.a_doubled; END;
CREATE FUNCTION public.a_rows() RETURNS SETOF public.a_doubled LANGUAGE sql AS $$ SELECT * FROM public.a_doubled ORDER BY id $$;
CREATE VIEW public.b_summary AS SELECT public.a_total() AS total;`

// crossDependencyResults 是用到这些视图与函数的查询结果。
func crossDependencyResults(t *testing.T, db *sql.DB) []string {
	t.Helper()
	return slices.Concat(queryLines(t, db, "SELECT total::text FROM public.b_summary"),
		queryLines(t, db, "SELECT r::text FROM public.a_rows() r"))
}

func dumpWhole(t *testing.T, db *sql.DB, database string, options dbdriver.DumpOptions) string {
	t.Helper()
	var out strings.Builder
	_, err := newSession(db).Dump(context.Background(), dbdriver.DumpRequest{
		Database: database, Whole: true, WithData: true, Writer: &out, Options: options,
		Header: dbdriver.DumpHeader{Version: "test", Asset: "pg", Time: time.Now()},
	})
	require.NoError(t, err)
	return out.String()
}

func runDump(t *testing.T, db *sql.DB, database, script string) {
	t.Helper()
	result, err := newSession(db).RunScript(context.Background(), dbdriver.ScriptRequest{
		Database: database, Script: strings.NewReader(script), Size: int64(len(script)),
	})
	require.NoError(t, err)
	require.Nil(t, result.Failure, "%+v", result.Failure)
	assert.Zero(t, result.Failed)
}

// 视图调用函数、函数引用视图（BEGIN ATOMIC、视图行类型）：按 pg_depend 的依赖排序后，文件在另一个名字的空库上
// 每条语句都成功，结构与查询结果一样；勾了「写入删除语句」时，文件运行回源库本身也成功（删除段按依赖倒序，
// 不带 CASCADE 也删得掉）。
func TestIntegrationDumpRestoresViewsAndFunctionsThatUseEachOther(t *testing.T) {
	admin := openDDLDatabase(t, os.Getenv("E2E_POSTGRES_DATABASE"))
	suffix := time.Now().UnixNano()
	source, target := fmt.Sprintf("opskat_dump_deps_src_%d", suffix), fmt.Sprintf("opskat_dump_deps_dst_%d", suffix)
	createScratchDatabase(t, admin, source)
	createScratchDatabase(t, admin, target)
	sourceDB, targetDB := openDDLDatabase(t, source), openDDLDatabase(t, target)
	_, err := sourceDB.Exec(crossDependencySQL)
	require.NoError(t, err)
	structure, results := queryLines(t, sourceDB, structureQuery), crossDependencyResults(t, sourceDB)
	require.Equal(t, []string{"70", "(1,20)", "(2,50)"}, results)

	t.Run("into an empty database", func(t *testing.T) {
		script := dumpWhole(t, sourceDB, source, structureOptions)
		t.Log(script)
		runDump(t, targetDB, target, script)
		assert.Equal(t, structure, queryLines(t, targetDB, structureQuery))
		assert.Equal(t, results, crossDependencyResults(t, targetDB))
	})
	t.Run("over the original database", func(t *testing.T) {
		options := structureOptions
		options.Drops = true
		runDump(t, sourceDB, source, dumpWhole(t, sourceDB, source, options))
		assert.Equal(t, structure, queryLines(t, sourceDB, structureQuery))
		assert.Equal(t, results, crossDependencyResults(t, sourceDB))
	})
}
