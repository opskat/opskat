package sqldb

import (
	"fmt"
	"strings"

	"github.com/opskat/opskat/pkg/dbdriver"
)

// 表设计器里列的两项能力：默认值按写法给出、新列自增。各由一个可选的方言接口开启——方言实现即开启，
// 驱动描述的 ExplicitDefaults / AutoIncrement 用 ClassifiesDefaults / AutoIncrements 从同一个方言得出，
// 声明与实现只有这一个来源。没开启的能力，Session 以 dbdriver.ErrUnsupported 拒绝用到它的请求。

// DefaultClassifier 是方言里「已有列的默认值是哪种写法」：实现它即开启默认值的四种写法。开启后建表 /
// 改表请求里的列可以给出写法（dbdriver.ColumnDefinition.DefaultKind），DefaultSQL 按写法写 DEFAULT；
// 改表读出的每一列（AlterableTable）经它判定写法，AlterTableModel 给出、比较改动也按判定后的写法与值。
type DefaultClassifier interface {
	// ClassifyDefault 判定已有列的默认值写法：column 是 AlterableTable 读出的一列，DefaultValue 是方言
	// 读到的原文，Row 是原始的一行。返回写法与按写法的值：「值」是不带引号与类型转换的原值，「表达式」
	// 是原样写回去的文本，无 / NULL 为空串。拿不准的写成表达式，原样写回不改变定义。
	ClassifyDefault(column AlterableColumn) (dbdriver.DefaultKind, string)
}

// AutoIncrementer 是方言里「自增列怎么写」：实现它即开启新表与新列的自增。方言读已有列时（AlterableTable）
// 同时给出自增的现状；已有列的自增不能改，由 Session 拒绝。
type AutoIncrementer interface {
	// AutoIncrementSQL 是自增列写在类型之后的子句（MySQL 的 AUTO_INCREMENT、PostgreSQL 的
	// GENERATED BY DEFAULT AS IDENTITY）；这一列不能自增（如类型不合）时返回 error。
	AutoIncrementSQL(column dbdriver.ColumnDefinition) (string, error)
}

// ClassifiesDefaults 报告方言开启了默认值的四种写法（实现了 DefaultClassifier），即驱动描述的
// ExplicitDefaults。
func ClassifiesDefaults(dialect Dialect) bool {
	_, ok := dialect.(DefaultClassifier)
	return ok
}

// AutoIncrements 报告方言开启了新表与新列的自增（实现了 AutoIncrementer），即驱动描述的 AutoIncrement。
func AutoIncrements(dialect Dialect) bool {
	_, ok := dialect.(AutoIncrementer)
	return ok
}

// NewTableAutoIncrementer 是开启了自增、但只能在新表上设的方言（如 SQLite：只有 INTEGER PRIMARY KEY
// 自增，ADD COLUMN 加不出主键）：改表时新增的列要自增，会话以 dbdriver.ErrUnsupported 拒绝。驱动描述的
// AutoIncrementNewTablesOnly 用 AutoIncrementsNewTablesOnly(dialect) 从同一个方言得出。
type NewTableAutoIncrementer interface {
	AutoIncrementer
	AutoIncrementsNewTablesOnly() bool
}

// AutoIncrementsNewTablesOnly 报告方言的自增只能在新表上设，即驱动描述的 AutoIncrementNewTablesOnly。
func AutoIncrementsNewTablesOnly(dialect Dialect) bool {
	limited, ok := dialect.(NewTableAutoIncrementer)
	return ok && limited.AutoIncrementsNewTablesOnly()
}

func columnFeatures(dialect Dialect) dbdriver.ColumnFeatures {
	return dbdriver.ColumnFeatures{
		ExplicitDefaults: ClassifiesDefaults(dialect), AutoIncrement: AutoIncrements(dialect),
		NewTablesOnly: AutoIncrementsNewTablesOnly(dialect),
	}
}

// DefaultSQL 把列的默认值写成 DEFAULT 后面的内容；没有默认值时 ok 为假。按写法写：无没有默认值，NULL 写
// NULL，值写成要存进这一列的字面量（literals 按括号前的类型名决定写法，同 Literals.Default 的非猜测
// 分支），表达式原样（首尾空白除外）。没给写法时照旧按文本猜（Literals.Default），空文本没有默认值。
func DefaultSQL(literals Literals, column dbdriver.ColumnDefinition) (literal string, ok bool, err error) {
	switch column.DefaultKind {
	case "":
		if strings.TrimSpace(column.DefaultValue) == "" {
			return "", false, nil
		}
		literal, err = literals.Default(column.DefaultValue, column.Type)
	case dbdriver.DefaultKindNone:
		return "", false, nil
	case dbdriver.DefaultKindNull:
		literal = "NULL"
	case dbdriver.DefaultKindValue:
		literal, err = literals.Literal(column.DefaultValue, typeName(column.Type))
	case dbdriver.DefaultKindExpression:
		literal = strings.TrimSpace(column.DefaultValue)
	default:
		return "", false, fmt.Errorf("column %q has unknown default kind %q", column.Name, column.DefaultKind)
	}
	if err != nil {
		return "", false, err
	}
	return literal, true, nil
}

// typeName 是类型文本括号前的类型名。
func typeName(columnType string) string {
	name, _, _ := strings.Cut(columnType, "(")
	return strings.TrimSpace(name)
}

// NewColumnSQL 是建表与新增列时的列定义，同 ColumnDefinitionSQL；要自增的列在类型之后写上方言的自增
// 子句（dialect 实现了 AutoIncrementer），方言没开启自增时返回包着 dbdriver.ErrUnsupported 的错误。
func NewColumnSQL(dialect Dialect, literals Literals, quote func(string) string, column dbdriver.ColumnDefinition) (string, error) {
	autoIncrement := ""
	if column.AutoIncrement {
		incrementer, ok := dialect.(AutoIncrementer)
		if !ok {
			return "", autoIncrementUnsupported(column)
		}
		clause, err := incrementer.AutoIncrementSQL(column)
		if err != nil {
			return "", err
		}
		autoIncrement = clause
	}
	return columnDefinitionSQL(literals, quote, column, autoIncrement)
}

func autoIncrementUnsupported(column dbdriver.ColumnDefinition) error {
	return fmt.Errorf("%w: this driver does not write auto-increment columns (column %q)", dbdriver.ErrUnsupported, column.Name)
}
